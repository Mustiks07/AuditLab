"""Minimal counterexamples on fresh seeds (protocol data-shortcuts-3.0, section 6).

Each case is generated by the checkout's own judge_adapter (separate process) with seeds 9360001... that
no analysis step saw, and reports input, expected and actual. `defect` is true when the generator still
has the property on every seed. Used by run.py (to confirm findings) and by docs/.../repro_v3.py.
"""
from __future__ import annotations

import csv, io, json, subprocess
from collections import Counter
from datetime import datetime
from fractions import Fraction
from pathlib import Path

from review.data_shortcuts.datasets import generate

SEEDS = [9360001, 9360002, 9360003]
B12 = {"config_version": "1.2", "company_size": {"ledger_rows_target": 400, "documents_target": 65}, "currencies": ["KZT", "USD"]}
ALLOC = {"kind": "allocation", "amount_minor": 1234567, "applied_bps": 5000, "tranches": 2}
CASES = {
    "CE1_profile_1.0_duplicate": {"issue_counts": {"duplicate_invoice": 1}},
    "CE1_profile_1.0_clean": {},
    "CE2_profile_1.0_allocation": {"issue_counts": {"payment_allocation": 1}},
    "CE2_profile_1.1_allocation": {"config_version": "1.1", "issue_counts": {"payment_allocation": 1}},
    "CE2_profile_1.2_allocation": {**B12, "issue_counts": {"payment_allocation": 1}},
    "CE3_profile_1.0_cutoff": {"issue_counts": {"period_cutoff": 1}},
    "CE4_profile_1.2_omitted_error": {**B12, "allocation_mode": "omitted", "issue_counts": {"payment_allocation": 1}, "financial_case": ALLOC},
    "CE4_profile_1.2_omitted_zero": {**B12, "allocation_mode": "omitted", "issue_counts": {"payment_allocation": 0}, "financial_case": ALLOC},
    "CE4_profile_1.2_duplicate_error": {**B12, "issue_counts": {"duplicate_invoice": 1}},
    "CE4_profile_1.2_duplicate_zero": {**B12, "issue_counts": {"duplicate_invoice": 0}},
    "CE5_profile_1.2_partial_three_tranches": {**B12, "issue_counts": {"payment_allocation": 1}, "financial_case": {**ALLOC, "tranches": 3, "applied_bps": 6100}},
    "CE5_profile_1.2_clean_three_tranches": {**B12, "issue_counts": {"payment_allocation": 0}, "financial_case": {**ALLOC, "tranches": 3, "applied_bps": 6100}},
}


def _load(d: Path):
    p = d / "public"
    return (json.loads((p / "manifest.json").read_text(encoding="utf-8")), list(csv.DictReader(io.StringIO((p / "ledger.csv").read_text(encoding="utf-8")))),
            [json.loads(l) for l in (p / "invoices.jsonl").read_text(encoding="utf-8").splitlines() if l.strip()],
            [json.loads(l) for l in (p / "payments.jsonl").read_text(encoding="utf-8").splitlines() if l.strip()],
            json.loads((d / "private" / "truth.json").read_text(encoding="utf-8")), json.loads((p / "policy.json").read_text(encoding="utf-8")))


def _affected(t):
    return {x.split("/", 1)[1] for i in t["issues"] for x in i["affected_ids"]}


def reproduce(checkout: Path, out: Path) -> dict:
    out.mkdir(parents=True, exist_ok=True)
    plan = [{"seed": s, "config": c, "dir": str(out / f"{name}-{s}")} for name, c in CASES.items() for s in SEEDS]
    gen = generate(checkout, plan, out / "gen")
    ep = lambda name, s: out / f"{name}-{s}"
    rep = {"checkout_sha": subprocess.run(["git", "rev-parse", "HEAD"], cwd=checkout, capture_output=True, text=True).stdout.strip(),
           "seeds": SEEDS, "inputs": CASES, "rejected": [g for g in gen if g["status"] == "rejected"]}
    if rep["rejected"]:
        return rep
    # CE1 -- profile 1.0: the duplicated invoice has one constant total, shared with the lawful archive copy
    dup = [sorted({d["total_minor"] for d in _load(ep("CE1_profile_1.0_duplicate", s))[2] if d["invoice_id"] in _affected(_load(ep("CE1_profile_1.0_duplicate", s))[4])}) for s in SEEDS]
    clean = [Counter(d["total_minor"] for d in _load(ep("CE1_profile_1.0_clean", s))[2]).most_common(2) for s in SEEDS]
    rep["CE1"] = {"title": "profile 1.0: the duplicated invoice always has the same total", "command_config": CASES["CE1_profile_1.0_duplicate"],
                  "expected": "the duplicated invoice's total depends on the seed", "actual_duplicated_totals": dup,
                  "clean_company_most_common_totals": clean, "defect": len({tuple(x) for x in dup}) == 1}
    # CE2 -- profiles 1.0 and 1.1: the partial application is exactly 3/5 of the designated payment
    ratios = {}
    for name in ("CE2_profile_1.0_allocation", "CE2_profile_1.1_allocation", "CE2_profile_1.2_allocation"):
        rs = []
        for s in SEEDS:
            m, led, inv, pay, t, pol = _load(ep(name, s)); dl = datetime.fromisoformat(pol["allocation"]["deadline"])
            pid = next(x.split("/", 1)[1] for i in t["issues"] for x in i["affected_ids"] if x.startswith("payment/"))
            amt = next(p["amount_minor"] for p in pay if p["payment_id"] == pid)
            applied = sum(int(r["debit_minor"]) for r in led if r["payment_id"] == pid and r["account"] == "UNAPPLIED" and datetime.fromisoformat(r["timestamp"]) < dl)
            rs.append(str(Fraction(applied, amt)))
        ratios[name] = rs
    rep["CE2"] = {"title": "profiles 1.0 and 1.1: exactly 3/5 of the designated payment is applied", "expected": "the applied share varies",
                  "actual_applied_share": ratios, "defect": {k: all(x == "3/5" for x in v) for k, v in ratios.items()}}
    # CE3 -- profile 1.0: the cutoff template (issued 23:59, recognised 00:01) and no lawful rows after the boundary
    hits, clean_after = [], []
    for s in SEEDS:
        m, led, inv, pay, t, pol = _load(ep("CE3_profile_1.0_cutoff", s)); end = datetime.fromisoformat(m["period_end"]); aff = _affected(t)
        after = [r for r in led if datetime.fromisoformat(r["timestamp"]) >= end]
        hits.append({"rows_after_boundary": len(after), "violating": sum(1 for r in after if r["invoice_id"] in aff or r["payment_id"] in aff),
                     "timestamps": sorted({r["timestamp"] for r in after}), "issued_at": sorted(d["issued_at"] for d in inv if d["invoice_id"] in aff)})
        m2, led2, *_ = _load(ep("CE1_profile_1.0_clean", s))
        clean_after.append(sum(1 for r in led2 if datetime.fromisoformat(r["timestamp"]) >= datetime.fromisoformat(m2["period_end"])))
    rep["CE3"] = {"title": "profile 1.0: every row after the boundary belongs to the violation; fixed 23:59 / 00:01 template",
                  "expected": "lawful postings also occur after the boundary and the times vary", "actual": hits, "clean_rows_after_boundary": clean_after,
                  "defect": all(h["rows_after_boundary"] == h["violating"] > 0 for h in hits) and not any(clean_after)
                  and len({(tuple(h["timestamps"]), tuple(x[11:] for x in h["issued_at"])) for h in hits}) == 1}
    # CE4 -- profile 1.2: the zero-issue company of the same seed/config differs in treasury journals (pair signal)
    tre = {}
    for kind in ("omitted", "duplicate"):
        tre[kind] = []
        for s in SEEDS:
            e, z = (_load(ep(f"CE4_profile_1.2_{kind}_{v}", s))[1] for v in ("error", "zero"))
            cnt = lambda led: len({r["journal_id"] for r in led if r["account"] == "CASH_RESERVE"})
            tre[kind].append({"error": cnt(e), "zero_issue": cnt(z), "ledger_rows": [len(e), len(z)]})
    rep["CE4"] = {"title": "profile 1.2: the zero-issue control has a different number of treasury journals", "expected": "equal counts",
                  "actual": tre, "defect": {k: all(d["error"] != d["zero_issue"] for d in v) for k, v in tre.items()}}
    # CE5 -- profile 1.2: the scenario payment's applied tranches are equal (+-1) in the error AND the lawful variant
    eq = {}
    for name in ("CE5_profile_1.2_partial_three_tranches", "CE5_profile_1.2_clean_three_tranches"):
        eq[name] = []
        for s in SEEDS:
            m, led, inv, pay, t, pol = _load(ep(name, s)); dl = datetime.fromisoformat(pol["allocation"]["deadline"])
            by = {}
            for r in led:
                if r["account"] == "UNAPPLIED" and int(r["debit_minor"]) > 0 and r["payment_id"] not in ("", "null") and datetime.fromisoformat(r["timestamp"]) < dl:
                    by.setdefault(r["payment_id"], []).append(int(r["debit_minor"]))
            equal = [p for p, v in by.items() if len(v) >= 2 and max(v) - min(v) <= 1]
            eq[name].append({"payments_with_equal_tranches": len(equal), "violating": sum(1 for p in equal if p in _affected(t)),
                             "tranches": [sorted(by[p]) for p in equal][:2]})
    rep["CE5"] = {"title": "profile 1.2: equal tranches mark the scenario payment (error and lawful variant)", "expected": "tranche sizes vary",
                  "actual": eq, "defect": all(x["payments_with_equal_tranches"] >= 1 for v in eq.values() for x in v)}
    return rep
