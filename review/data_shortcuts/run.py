"""Data-shortcut review (protocol data-shortcuts-3.0, Claude Pro 2). Internal measurements, not a jury score.

    python review/data_shortcuts/run.py --out OUT_DIR [--checkout PATH] [--per-stratum 8] [--per-cell 6] [--resamples 10000]

--checkout is the repository whose generator and published datasets are tested (default: this one).
Episodes are generated by that checkout's judge_adapter in a separate process; the analysis is this
reviewer's code. The integrator can point --checkout at any branch (e.g. Claude Pro 1's) and compare
`regressions` with the published report of main. Exit code: 0 always; read `regressions`.
"""
from __future__ import annotations

import argparse, json, subprocess, sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from review.data_shortcuts import datasets as ds, companies as co, diversity  # noqa: E402
from review.data_shortcuts.analysis import analyse, load  # noqa: E402
from review.data_shortcuts.heuristics import evaluate, flag  # noqa: E402

PROTOCOL_ID = "data-shortcuts-3.0"
C_FRESH_START, B_FRESH_START = 9350001, 9370001
# Rule -> minimal counterexample that must reproduce on fresh seeds before a finding is confirmed (section 5)
COUNTEREXAMPLE = {("A", "ledger", "ratio_linked"): "CE2", ("A", "ledger", "ratio_is_fixed"): "CE2", ("A", "ledger", "hour"): "CE3",
                  ("A", "ledger", "day"): "CE3", ("A", "invoices", "minute"): "CE3", ("A", "invoices", "hour"): "CE3",
                  ("A", "invoices", "day"): "CE3", ("A", "invoices", "minutes_to_boundary"): "CE3", ("C", "invoices", "amount_repeat"): "CE1",
                  ("B", "payments", "equal_tranches"): "CE5"}


def sha(path: Path) -> str:
    return subprocess.run(["git", "rev-parse", "HEAD"], cwd=path, capture_output=True, text=True).stdout.strip()


def strong(e: dict, min_pos: int = 20) -> bool:
    return e["precision"] is not None and e["precision"] >= 0.5 and (e["lift"] or 0) >= 10 and (e["recall"] or 0) >= 0.2 and e["positives"] >= min_pos


def merge_families_a(items: list[dict]) -> None:
    """Set A: one economic origin = at least half of the commercial chains shared (union-find)."""
    from review.agent_generalization.canonical import chains
    ch = {it["dir"]: {c["digest"] for c in chains(Path(it["dir"]) / "public").values() if c["canon"]["invoices"] or c["canon"]["payments"]} for it in items}
    parent = {d: d for d in ch}
    def find(x):
        while parent[x] != x: x = parent[x]
        return x
    keys = sorted(ch)
    for i, a in enumerate(keys):
        for b in keys[i + 1:]:
            if len(ch[a] & ch[b]) >= 0.5 * min(len(ch[a]), len(ch[b])):
                parent[find(b)] = find(a)
    for it in items:
        it["family"] = "A:" + Path(find(it["dir"])).name


def transfer(rules: list[dict], target_rows: list[dict], label: str) -> list[dict]:
    """Apply rules chosen elsewhere, unchanged, to every record of another set (no re-selection)."""
    out = []
    for r in rules:
        rows = [x for x in target_rows if x["table"] == r["table"]]
        e = evaluate(rows, r["feature"], tuple(r["rule"]), r["target"], 2000)
        out.append({"to": label, "table": r["table"], "target": r["target"], "feature": r["feature"], "rule": r["rule"], "evaluate": e, "strong": strong(e)})
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, required=True); ap.add_argument("--checkout", type=Path, default=ROOT)
    ap.add_argument("--per-stratum", type=int, default=8); ap.add_argument("--per-cell", type=int, default=6)
    ap.add_argument("--resamples", type=int, default=10000)
    a = ap.parse_args(argv)
    out, ck = a.out.resolve(), a.checkout.resolve()
    out.mkdir(parents=True, exist_ok=True)
    odd = lambda it: "explore" if int(it["family"][1:]) % 2 == 1 else "evaluate"
    # ---------------------------------------------------------------- the three sets (+ fresh seeds of C)
    A = ds.plan_a(ck); merge_families_a(A)
    B = ds.generate(ck, ds.plan_b(out / "B", a.per_stratum), out / "gen-B")
    C = ds.generate(ck, ds.plan_c(out / "C", a.per_cell), out / "gen-C")
    Cf = ds.generate(ck, [{**p, "family": "F" + p["family"][1:]} for p in plan_c_fresh(out / "C-fresh", a.per_cell)], out / "gen-C-fresh")
    Bf = ds.generate(ck, ds.plan_b(out / "B-fresh", max(2, a.per_stratum // 2), B_FRESH_START, "G"), out / "gen-B-fresh")
    rows = {"A": load(A, lambda it: "explore" if it["split_name"] == "train" else "evaluate"), "B": load(B, odd), "C": load(C, odd),
            "C_fresh": load(Cf, lambda it: "evaluate"), "B_fresh": load(Bf, lambda it: "evaluate")}
    report = {"protocol_id": PROTOCOL_ID, "reviewer_sha": sha(ROOT), "checkout_sha": sha(ck), "not_a_jury_score": True,
              "generation": {k: dict(Counter(x["status"] for x in v)) for k, v in (("B", B), ("C", C), ("C_fresh", Cf), ("B_fresh", Bf))},
              "sets": {}, "transfer": {}, "companies": {}, "diversity": None, "findings": [], "regressions": []}
    for k in ("A", "B", "C"):
        res = analyse(rows[k], a.resamples)
        report["sets"][k] = res
    # ---------------------------------------------------------------- reproduction on other data, rules unchanged
    by_c_version = lambda v: [r for r in rows["C_fresh"] if r["stratum"].startswith(v)]
    sel = lambda k: [r for r in report["sets"][k]["rules"] if r["status"] in ("confirmed", "hypothesis") and r["class"] != "financial"]
    report["transfer"]["A_rules_on_fresh_adapter_default"] = transfer(sel("A"), by_c_version("adapter-default"), "C_fresh adapter default")
    report["transfer"]["A_rules_on_fresh_profile_1.1_adapter"] = transfer(sel("A"), by_c_version("1.1"), "C_fresh profile 1.1")
    report["transfer"]["A_rules_on_profile_1.2"] = transfer(sel("A"), rows["B"], "B profile 1.2")
    report["transfer"]["C_rules_on_fresh_seeds"] = transfer(sel("C"), rows["C_fresh"], "C_fresh")
    report["transfer"]["B_rules_on_fresh_seeds"] = transfer(sel("B"), rows["B_fresh"], "B_fresh")
    report["transfer"]["B_rules_on_fresh_profile_1.1_adapter"] = transfer(sel("B"), by_c_version("1.1"), "C_fresh profile 1.1")
    from review.data_shortcuts.counterexamples import reproduce
    report["counterexamples"] = reproduce(ck, out / "counterexamples")
    # ---------------------------------------------------------------- companies, pairs, diversity
    for k, items, part in (("A", A, lambda it: "explore" if it["split_name"] == "train" else "evaluate"), ("B", B, odd), ("C", C, odd)):
        c = co.analyse(items, part, a.resamples)
        report["companies"][k] = {"companies": c["companies"], "rules": c["rules"]}
        if k == "B":
            report["companies"]["B_paired_error_vs_zero_issue"] = co.paired(c["rows"])
    div = diversity.run(B)
    report["diversity"] = {k: div[k] for k in ("situations", "clean_control_p9", "companies_with_lookalike", "companies")}
    report["diversity"]["failed_rows"] = [r for r in div["rows"] if r["status"] != "passed"][:10]
    report["diversity"]["failed_pairs"] = [p for p in div["pairs"] if p["status"] != "passed"][:10]
    # programmatic financial adjudication: a payments rule that flags exactly the designated payments whose whole
    # amount is still unapplied before the deadline is the allocation policy itself, not a generator hint
    report["financial_adjudication"] = {}
    for k in ("A", "B", "C"):
        pays = [r for r in rows[k] if r["table"] == "payments"]
        for r in report["sets"][k]["rules"]:
            if r["table"] == "payments" and r["class"] != "financial":
                same = all(flag(x, r["feature"], tuple(r["rule"])) == bool(x["full_unapplied"] == 1) for x in pays)
                if same:
                    report["financial_adjudication"][f"{k}:{r['feature']} {r['rule'][0]} {r['rule'][1]}"] = {
                        "payments": len(pays), "flags_equal_full_unapplied_balance": True,
                        "all_flagged_are_violations": all(x["affected"] for x in pays if x["full_unapplied"] == 1)}
    findings(report)
    regressions(report)
    (out / "data-shortcuts-report.json").write_text(json.dumps(report, indent=1, default=str), encoding="utf-8")
    print(json.dumps({"checkout_sha": report["checkout_sha"], "findings": [(f["id"], f["status"], f["title"]) for f in report["findings"]],
                      "regressions": [(r["id"], r["status"]) for r in report["regressions"]]}, indent=1))
    return 0


def plan_c_fresh(work: Path, per_cell: int) -> list[dict]:
    plan = ds.plan_c(work, per_cell)
    for k, p in enumerate(plan):
        p["seed"] = C_FRESH_START + k
    return plan


def _ce_defect(report, ce):
    d = (report.get("counterexamples") or {}).get(ce, {}).get("defect")
    return any(d.values()) if isinstance(d, dict) else bool(d)


def findings(report: dict) -> None:
    """Confirmed = protocol thresholds on the evaluation part AND its minimal counterexample reproduces on fresh seeds
    (or, without a counterexample, the unchanged rule is strong again on fresh seeds)."""
    fresh = {"A": report["transfer"]["A_rules_on_fresh_adapter_default"], "C": report["transfer"]["C_rules_on_fresh_seeds"],
             "B": report["transfer"]["B_rules_on_fresh_seeds"]}
    implied = set(report["financial_adjudication"])
    for k in ("A", "B", "C"):
        for r in report["sets"][k]["rules"]:
            if r["class"] == "financial" or r["status"] == "nothing_found":
                continue
            key = (r["table"], r["feature"], tuple(r["rule"]))
            again = next((t for t in fresh.get(k, []) if (t["table"], t["feature"], tuple(t["rule"]), t["target"]) == (*key, r["target"])), None)
            ce = COUNTEREXAMPLE.get((k, r["table"], r["feature"]))
            reproduced = (ce is not None and _ce_defect(report, ce)) or bool(again and again["strong"])
            if f"{k}:{r['feature']} {r['rule'][0]} {r['rule'][1]}" in implied:
                status = "financial_signal"
            elif r["status"] == "confirmed" and reproduced:
                status = "confirmed"
            elif r["status"] == "confirmed" or (again and again["strong"]):
                status = "hypothesis"
            else:
                status = r["status"]
            e = r["evaluate"]
            report["findings"].append({"id": f"{k}:{r['table']}:{r['target']}:{r['feature']}", "set": k, "status": status, "class": r["class"],
                                       "counterexample": ce, "counterexample_reproduced": ce is not None and _ce_defect(report, ce),
                                       "title": f"{r['table']} {r['feature']} {r['rule'][0]} {r['rule'][1]} -> {r['target']}",
                                       "evaluate": {x: e[x] for x in ("records", "positives", "base_rate", "flagged", "precision", "recall", "lift",
                                                                       "flags_in_clean_companies", "clean_companies_accused", "clean_companies", "precision_ci95")},
                                       "fresh_seeds": again and {x: again["evaluate"][x] for x in ("records", "positives", "precision", "recall", "lift", "flags_in_clean_companies")}})


def regressions(report: dict) -> None:
    def add(rid, prop, ok, actual, expected):
        report["regressions"].append({"id": rid, "property": prop, "status": "passed" if ok else "failed", "expected": expected, "actual": actual})
    conf = lambda k: [f["title"] for f in report["findings"] if f["set"] == k and f["status"] == "confirmed"]
    add("R1", "profile 1.2: no confirmed artificial or context record rule", not conf("B"), conf("B"), [])
    add("R2", "adapter with a typical configuration: no confirmed record rule", not conf("C"), conf("C"), [])
    add("R3", "published train/dev: no confirmed record rule", not conf("A"), conf("A"), [])
    p = report["companies"]["B_paired_error_vs_zero_issue"]["treasury_journals"]
    add("R4", "profile 1.2 zero-issue control keeps the treasury journal count of its error company", p["equal"] == p["pairs"],
        {k: p[k] for k in ("pairs", "error_greater", "equal", "error_smaller", "differing_by_stratum")}, "equal in every pair")
    s = report["diversity"]["situations"]
    add("R5", "profile 1.2: every stratum realises its financial situation", all(set(v) == {"passed"} for v in s.values()), s, "all passed")
    pc = report["diversity"]["clean_control_p9"]
    add("R6", "profile 1.2: every zero-issue control keeps the commercial history (P9)", all(set(v) == {"passed"} for v in pc.values()), pc, "all passed")
    fa = {k: v for k, v in report["financial_adjudication"].items() if k.startswith("B:")}
    add("R7", "profile 1.2: the omission signal is the allocation rule itself (every flagged payment has its whole amount unapplied)",
        bool(fa) and all(v["all_flagged_are_violations"] for v in fa.values()), fa, "non-empty, all flagged are violations")
    ce = report.get("counterexamples", {})
    add("R9", "profile 1.2: the applied share is not fixed at 3/5", not ce.get("CE2", {}).get("defect", {}).get("CE2_profile_1.2_allocation", True),
        ce.get("CE2", {}).get("actual_applied_share"), "varies")
    comp = [(k, r["feature"]) for k in ("A", "B", "C") for r in report["companies"][k]["rules"] if strong(r["evaluate"], 10)]
    add("R8", "no company-level count separates companies with a violation from clean ones", not comp, comp, [])


if __name__ == "__main__":
    raise SystemExit(main())
